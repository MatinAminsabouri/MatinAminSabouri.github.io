/**
 * build-icons.mjs — regenerates the inline icon sprite from ionicons SVGs.
 *
 * The sprite is inlined into index.html (between BUILD:ICONS markers) so the
 * page needs no third-party icon CDN at runtime. Run after adding an icon:
 *   node scripts/build-icons.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ICON_DIR = process.env.IONICONS_DIR || 'scripts/icons';
const OUT = 'assets/icons/sprite.svg.html';

const files = fs.readdirSync(ICON_DIR).filter((f) => f.endsWith('.svg')).sort();

const symbols = files.map((file) => {
  const name = file.replace(/\.svg$/, '');
  const svg = fs.readFileSync(path.join(ICON_DIR, file), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 512 512';

  let inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .trim();

  const isOutline = /fill="none"/.test(inner);
  if (!isOutline) {
    /* solid glyphs (brand marks) are filled shapes. The wrapper CSS strokes
       outline icons, so these paths must opt out explicitly — a presentation
       attribute beats the inherited value. */
    inner = inner
      .replace(/<path(?![^>]*\bfill=)/g, '<path fill="currentColor"')
      .replace(/<path(?![^>]*\bstroke=)/g, '<path stroke="none"');
  }

  return `  <symbol id="i-${name}" viewBox="${viewBox}">${inner}</symbol>`;
});

const sprite = `<!-- Generated by scripts/build-icons.mjs — do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" class="icon-sprite" aria-hidden="true" focusable="false">
${symbols.join('\n')}
</svg>`;

fs.writeFileSync(OUT, sprite + '\n');
console.log(`sprite: ${files.length} symbols, ${sprite.length} bytes -> ${OUT}`);
